"""Render the canonical SIAM News Markdown feature as a compact LaTeX proof.

No external dependencies. All prose and bibliography are read from article/feature.md;
figures refer to committed ProximityGraphs-generated PNGs. Reproducible commands:

    python scripts/render_article.py
    cd article && pdflatex -halt-on-error main.tex

The output is a magazine-style author proof, NOT an official SIAM journal template.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "article" / "feature.md"
DESTINATION = ROOT / "article" / "main.tex"

PREAMBLE = r"""% AUTO-GENERATED from article/feature.md by scripts/render_article.py.
% Do not edit this file directly. SIAM News proposal, not submitted.
\documentclass[10pt,letterpaper]{article}
\usepackage[T1]{fontenc}
\usepackage[utf8]{inputenc}
\usepackage[margin=18mm]{geometry}
\usepackage{lmodern,microtype,graphicx,amsmath,amssymb,xcolor,parskip,hyperref,caption,float}
\definecolor{ProxTeal}{HTML}{166B75}
\definecolor{ProxInk}{HTML}{253C49}
\definecolor{ProxGray}{HTML}{60717B}
\hypersetup{colorlinks=true,urlcolor=ProxTeal,linkcolor=ProxTeal,
 pdfauthor={Heriberto Espino-Montelongo; Hector Maravillo; Diego Villarreal de la Cerda},
 pdftitle={Who Counts as a Neighbor?}}
\captionsetup{font=footnotesize,labelfont={bf,color=ProxInk},
 justification=raggedright,singlelinecheck=false}
\renewcommand{\familydefault}{\sfdefault}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0.22em}
\raggedbottom
\newcommand{\featurefigure}[3]{%
\begin{figure}[H]\centering
\IfFileExists{../site/assets/#1.png}
 {\includegraphics[width=.57\linewidth]{../site/assets/#1.png}}
 {\fbox{\parbox[c][28mm][c]{.65\linewidth}{\centering #1.png}}}
\caption{#2 \href{#3}{Explore the interactive figure}.}
\end{figure}%
}
\begin{document}
\begin{center}
{\footnotesize\bfseries\color{ProxTeal} SOFTWARE AND PROGRAMMING
 \quad \textbullet\quad SIAM NEWS AUTHOR DRAFT}\\[7pt]
{\LARGE\bfseries\color{ProxInk} Who Counts as a Neighbor?}\\[4pt]
{\large\color{ProxGray} From empty regions to AI, topology, and stochastic geometry}\\[8pt]
{\small\textbf{Heriberto Espino-Montelongo} (Universidad de las Am\'ericas Puebla)}\\[2pt]
{\small\textbf{H\'ector Maravillo} (UAM, Mexico) \quad
\textbf{Diego Villarreal de la Cerda} (T-Systems)}\\[3pt]
{\scriptsize\color{ProxGray} Affiliations and byline subject to coauthor approval; not submitted.}
\end{center}
\vspace{3pt}\hrule\vspace{8pt}
"""

FOOTER = r"\end{document}" + "\n"
FIGURES = {"1": "figure01-water", "2": "figure02-habitat", "3": "figure03-sensors"}


def tex_escape(value: str) -> str:
    substitutions = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
        "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
        # Handle Greek letters even *inside* bold or linked text: those spans
        # are escaped before the regular inline-math substitution stage.
        "α": r"\ensuremath{\alpha}", "β": r"\ensuremath{\beta}",
        "γ": r"\ensuremath{\gamma}",
        "$": r"\$", "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}", "—": "---", "–": "--",
    }
    return "".join(substitutions.get(c, c) for c in value)


def inline_md(value: str) -> str:
    """Escape prose while preserving existing math and converting basic Markdown."""
    placeholders: list[str] = []

    def hold(value: str) -> str:
        i = len(placeholders)
        placeholders.append(value)
        return f"ZZZPROXPLACEHOLDER{i}ZZZ"

    # First protect literal math, links and inline code, before escaping prose.
    value = re.sub(r"\\\[[\s\S]*?\\\]", lambda m: hold(m.group(0)), value)
    value = re.sub(r"\\\([\s\S]*?\\\)", lambda m: hold(m.group(0)), value)
    value = re.sub(
        r"\[([^\]]+)\]\((https?://[^)]+)\)",
        lambda m: hold(r"\href{" + m.group(2).replace("#", r"\#") + "}{" +
                       tex_escape(m.group(1)) + "}"),
        value,
    )
    value = re.sub(r"https?://[^\s)]+", lambda m: hold(
        r"\url{" + m.group(0).rstrip(".") + "}"), value)
    value = re.sub(r"`([^`]+)`", lambda m: hold(r"\texttt{" + tex_escape(m.group(1)) + "}"), value)
    value = re.sub(r"\*\*([^*]+)\*\*", lambda m: hold(
        r"\textbf{" + tex_escape(m.group(1)) + "}"), value)
    value = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", lambda m: hold(
        r"\emph{" + tex_escape(m.group(1)) + "}"), value)
    for c, macro in {"β": r"\(\beta\)", "α": r"\(\alpha\)",
                     "≥": r"\(\geq\)", "≤": r"\(\leq\)"}.items():
        value = value.replace(c, hold(macro))
    value = tex_escape(value)
    # Restore in reverse order: nested Markdown (e.g. bold hyperlinks) can
    # contain a previously allocated placeholder inside a later one.
    for i in reversed(range(len(placeholders))):
        value = value.replace(f"ZZZPROXPLACEHOLDER{i}ZZZ", placeholders[i])
    return value


def make_body(source: str) -> str:
    if "<!-- ARTICLE_BODY_START -->" not in source:
        raise ValueError("Missing <!-- ARTICLE_BODY_START --> marker")
    body = source.split("<!-- ARTICLE_BODY_START -->", 1)[1].split("## References", 1)[0]
    output: list[str] = []
    figure_count = 0
    for para in re.split(r"\n\s*\n", body.strip()):
        para = para.strip()
        if not para:
            continue
        if para.startswith("## "):
            output.append(r"\section*{" + tex_escape(para[3:]) + "}")
            continue
        if para.startswith("**Figure "):
            m = re.match(r"\*\*Figure ([123])\.\*\*\s+([\s\S]+)", para)
            if not m:
                raise ValueError("Malformed figure caption: " + para[:80])
            number, raw = m.groups()
            link = re.search(r"\[([^\]]+)\]\((https?://[^)]+)\)\.?$", raw.strip())
            if not link:
                raise ValueError("Missing interactive link for Figure " + number)
            caption = raw[:link.start()].strip().rstrip(".")
            output.append(
                r"\featurefigure{" + FIGURES[number] + "}{" +
                inline_md(caption) + "}{" +
                link.group(2).replace("#", r"\#") + "}"
            )
            figure_count += 1
            continue
        if para.startswith(r"\[") and para.endswith(r"\]"):
            output.append(para)
            continue
        output.append(inline_md(re.sub(r"\s*\n\s*", " ", para)))
    if figure_count != 3:
        raise ValueError(f"Expected 3 feature figures; found {figure_count}")
    return "\n\n".join(output) + "\n"


def make_references(source: str) -> str:
    refs = source.split("## References", 1)[1].split("## About the authors", 1)[0]
    entries = [v.strip() for v in re.split(r"\n\s*\n", refs.strip()) if v.strip()]
    if not 1 <= len(entries) <= 10:
        raise ValueError(f"SIAM News reference limit exceeded: {len(entries)}")
    # The ten APA-style entries are supplementary metadata. Set them compactly
    # so that the three biographies do not spill onto an otherwise empty page.
    chunks = [r"\renewcommand{\refname}{References}", r"\begingroup",
              r"\footnotesize", r"\begin{thebibliography}{10}",
              r"\setlength{\itemsep}{1pt}", r"\setlength{\parsep}{0pt}"]
    for i, entry in enumerate(entries, 1):
        chunks.append(r"\bibitem{source" + str(i) + "} " +
                      inline_md(re.sub(r"\s*\n\s*", " ", entry)))
    chunks.append(r"\end{thebibliography}")
    chunks.append(r"\endgroup")
    return "\n".join(chunks) + "\n"


def make_bios(source: str) -> str:
    bios = source.split("## About the authors", 1)[1]
    bios = bios.split("*Editorial note:", 1)[0]
    entries = [v.strip() for v in re.split(r"\n\s*\n", bios.strip()) if v.strip()]
    if len(entries) != 3:
        raise ValueError(f"Expected three author biographies, found {len(entries)}")
    return r"\section*{About the authors}" + "\n" + "\n\n".join(
        inline_md(v) for v in entries) + "\n"


def main() -> None:
    source = SOURCE.read_text(encoding="utf-8")
    out = PREAMBLE + make_body(source) + "\n" + make_references(source) + \
          "\n" + make_bios(source) + "\n" + FOOTER
    if "ZZZPROXPLACEHOLDER" in out:
        raise ValueError("Unresolved inline formatting placeholder in generated TeX")
    if r"\textbackslash{}[" in out or r"\textbackslash{}]" in out:
        raise ValueError("Escaped display-math delimiter in generated TeX")
    DESTINATION.write_text(out, encoding="utf-8")
    print(f"Rendered {DESTINATION.relative_to(ROOT)} from article/feature.md")


if __name__ == "__main__":
    main()
